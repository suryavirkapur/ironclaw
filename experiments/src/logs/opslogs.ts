import { FIRST_NAMES, LAST_NAMES, mulberry32, pick, randInt } from '../db/seed.js';

export const OPS_LOG_SEED = 7;
export const DAY_COUNT = 6;

const EVENT_TYPES = ['BKG', 'CXL', 'RFD', 'DLY', 'PING'] as const;
type EventType = (typeof EVENT_TYPES)[number];

const NOTES = ['plans changed', 'duplicate booking', 'meeting moved', 'illness', 'schedule conflict'];
const CHANNELS = ['web', 'mobile', 'agent'];
const DELAY_REASONS = ['weather', 'late crew', 'ATC slot', 'technical check'];
const NODES = ['eu-west-1', 'us-east-2', 'ap-south-1'];

/**
 * In-memory store of IronAir "ops export" files: one legacy-format log file per day.
 * Deterministic for a given seed so every scenario sees byte-identical files.
 */
export interface OpsLogStore {
  list(): string[];
  read(name: string): string;
}

/**
 * The legacy format is deliberately hostile to naive parsing:
 *   ## IRONAIR OPS EXPORT day=2026-07-20
 *   ## fx: 1 EUR = 1.07 USD
 *   [09:16:02Z] CXL pax="Fischer, Ravi" ref=ZTQLWU amt=571.00USD flt=IC135 note="plans changed"
 * - key=value pairs in arbitrary order, values optionally quoted (and may contain commas/spaces)
 * - amounts in USD or EUR; the EUR->USD rate is in each file's own header and varies per day
 * - comment (#) lines and PING heartbeat noise interleaved anywhere
 */
export function createOpsLogStore(seed: number = OPS_LOG_SEED): OpsLogStore {
  const files = new Map<string, string>();
  for (let day = 1; day <= DAY_COUNT; day++) {
    files.set(fileName(day), generateDayFile(mulberry32(seed + day), day));
  }
  return {
    list: () => [...files.keys()].sort(),
    read: (name: string) => {
      const content = files.get(name);
      if (content === undefined) {
        throw new Error(`No such file "${name}". Available: ${[...files.keys()].sort().join(', ')}`);
      }
      return content;
    },
  };
}

export function fileName(day: number): string {
  return `day-${String(day).padStart(2, '0')}.log`;
}

// ---------------------------------------------------------------------------
// Generator
// ---------------------------------------------------------------------------

function generateDayFile(rng: () => number, day: number): string {
  const date = `2026-07-${19 + day}`;
  const fx = Math.round((1.05 + rng() * 0.1) * 1000) / 1000;

  const lines: string[] = [
    `## IRONAIR OPS EXPORT day=${date}`,
    `## fx: 1 EUR = ${fx.toFixed(3)} USD`,
    '# auto-generated by ironair-opsd; do not edit',
    '',
  ];

  const eventCount = randInt(rng, 34, 42);
  let cxlCount = 0;
  for (let i = 0; i < eventCount; i++) {
    // Guarantee at least 3 cancellations per day.
    const type: EventType = i >= eventCount - 3 && cxlCount < 3 ? 'CXL' : pick(rng, EVENT_TYPES);
    if (type === 'CXL') cxlCount += 1;
    if (rng() < 0.12) lines.push(pick(rng, ['# checkpoint ok', '# queue drained', '# snapshot written', '']));
    lines.push(eventLine(rng, type));
  }
  return lines.join('\n') + '\n';
}

function eventLine(rng: () => number, type: EventType): string {
  const time = `${pad2(randInt(rng, 0, 23))}:${pad2(randInt(rng, 0, 59))}:${pad2(randInt(rng, 0, 59))}Z`;
  return `[${time}] ${type} ${shuffledFields(rng, type).join(' ')}`;
}

/** Builds the key=value pairs of one event in random order with random quoting. */
function shuffledFields(rng: () => number, type: EventType): string[] {
  const fields: string[] = [];
  // Values that can contain spaces/commas must always be quoted to stay parseable.
  const kv = (key: string, value: string, quotable = false): string =>
    quotable ? `${key}="${value}"` : `${key}=${value}`;

  if (type === 'PING') {
    fields.push(kv('node', pick(rng, NODES)));
  } else if (type === 'DLY') {
    fields.push(kv('flt', flightNumber(rng)));
    fields.push(kv('mins', String(randInt(rng, 15, 240))));
    fields.push(kv('reason', pick(rng, DELAY_REASONS), true));
  } else {
    const cents = randInt(rng, 80, 1400) * 100;
    const inEur = rng() < 0.45;
    fields.push(kv('ref', reference(rng)));
    fields.push(kv('pax', `${pick(rng, LAST_NAMES)}, ${pick(rng, FIRST_NAMES)}`, true));
    fields.push(kv('amt', `${(cents / 100).toFixed(2)}${inEur ? 'EUR' : 'USD'}`));
    fields.push(kv('flt', flightNumber(rng)));
    if (type === 'BKG') fields.push(kv('ch', pick(rng, CHANNELS)));
    if ((type === 'CXL' || type === 'RFD') && rng() < 0.7) fields.push(kv('note', pick(rng, NOTES), true));
    if (rng() < 0.3) fields.push(kv('src', pick(rng, CHANNELS)));
  }

  // Fisher-Yates shuffle so field order is unpredictable.
  for (let i = fields.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    const a = fields[i];
    const b = fields[j];
    if (a !== undefined && b !== undefined) {
      fields[i] = b;
      fields[j] = a;
    }
  }
  return fields;
}

function flightNumber(rng: () => number): string {
  return `IC${randInt(rng, 101, 139)}`;
}

function reference(rng: () => number): string {
  const alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  return Array.from({ length: 6 }, () => alphabet[Math.floor(rng() * alphabet.length)]).join('');
}

function pad2(n: number): string {
  return String(n).padStart(2, '0');
}

// ---------------------------------------------------------------------------
// Reference parser used as deterministic ground truth
// ---------------------------------------------------------------------------

export interface CancellationEvent {
  ref: string;
  passenger: string;
  amountUsd: number;
  flight: string;
  time: string;
  note: string | null;
}

interface ParsedHeader {
  day: string;
  fxEurToUsd: number;
}

/** Extracts all cancellation events from a log file, normalized and converted to USD. */
export function extractCancellations(text: string): CancellationEvent[] {
  const header = parseHeader(text);
  const events: CancellationEvent[] = [];

  for (const line of text.split('\n')) {
    const match = /^\[(\d{2}:\d{2}:\d{2}Z)\]\s+([A-Z]+)\s+(.*)$/.exec(line.trim());
    if (!match || match[2] !== 'CXL') continue;
    const fields = parseFields(match[3] ?? '');
    const amountUsd = toUsd(fields['amt'], header.fxEurToUsd);
    if (fields['ref'] && fields['pax'] && amountUsd !== null && fields['flt']) {
      events.push({
        ref: fields['ref'],
        passenger: fields['pax'],
        amountUsd,
        flight: fields['flt'],
        time: `${header.day}T${match[1] ?? ''}`,
        note: fields['note'] ?? null,
      });
    }
  }
  return events;
}

function parseHeader(text: string): ParsedHeader {
  const day = /day=(\d{4}-\d{2}-\d{2})/.exec(text)?.[1] ?? 'unknown';
  const fx = Number(/fx:\s*1 EUR = ([\d.]+) USD/.exec(text)?.[1] ?? '1');
  return { day, fxEurToUsd: fx };
}

/** Tokenizes `k=v k="v v" ...` respecting quoted values. */
function parseFields(rest: string): Record<string, string> {
  const fields: Record<string, string> = {};
  for (const match of rest.matchAll(/(\w+)="([^"]*)"|(\w+)=(\S+)/g)) {
    const key = match[1] ?? match[3];
    const value = match[2] ?? match[4];
    if (key && value !== undefined) fields[key] = value;
  }
  return fields;
}

function toUsd(amt: string | undefined, fxEurToUsd: number): number | null {
  const match = /^([\d.]+)(USD|EUR)$/.exec(amt ?? '');
  if (!match) return null;
  const value = Number(match[1]);
  const usd = match[2] === 'EUR' ? value * fxEurToUsd : value;
  return Math.round(usd * 100) / 100;
}
